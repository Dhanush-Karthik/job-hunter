import { test, expect } from '../fixtures'

test('real API: evaluate, approve CV, record applied, move to Screening and count the call', async ({ page }) => {
  test.setTimeout(60_000)
  await page.goto('/leads')
  const row = page.getByRole('row').filter({ hasText: 'Offline Browser Co' })
  await expect(row).toContainText('New')
  await row.getByRole('link', { name: 'Java Backend Engineer', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Java Backend Engineer', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Shortlist', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Shortlist', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Evaluate', exact: true }).click()
  await page.getByRole('tab', { name: 'Evaluation report', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Machine Summary', exact: true })).toBeVisible({ timeout: 20_000 })
  await expect(page.getByRole('button', { name: 'Re-evaluate', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Generate CV A', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Approve CV', exact: true })).toBeVisible({ timeout: 20_000 })
  // Rendering the fake PDF still exercises the real PDF endpoint and browser preview.
  await expect(page.locator('canvas').first()).toBeVisible()
  await page.getByRole('button', { name: 'Approve CV', exact: true }).click()
  await expect(page.getByText('Approved', { exact: true })).toBeVisible()
  await expect(page.getByRole('list', { name: 'Application timeline' })).toContainText('Shortlisted → Ready')
  await page.getByRole('button', { name: 'Mark applied', exact: true }).click()
  await expect(page.getByRole('list', { name: 'Application timeline' })).toContainText('Ready → Applied')
  const nav = page.getByRole('navigation', { name: 'Main' })
  await nav.getByRole('link', { name: 'Tracker', exact: true }).click()
  const card = page.getByRole('link', { name: 'Offline Browser Co: Java Backend Engineer', exact: true })
  await expect(page.getByRole('region', { name: 'Applied column' })).toContainText('Offline Browser Co')
  await expect(card).toBeVisible()
  await page.getByRole('combobox', { name: 'Move Offline Browser Co to', exact: true }).selectOption('Screening')
  await expect(page.getByRole('region', { name: 'Screening column' })).toContainText('Offline Browser Co')
  await expect(page.getByRole('region', { name: 'Applied column' })).not.toContainText('Offline Browser Co')
  await nav.getByRole('link', { name: 'Today', exact: true }).click()
  await expect(page.getByLabel('1 interview calls this week', { exact: true })).toBeVisible()
})

test('real API: settings save survives a page reload', async ({ page, request }) => {
  await page.goto('/settings')
  const topN = page.getByRole('spinbutton', { name: 'Auto-evaluate top N per day', exact: true })
  await expect(topN).toBeVisible()
  await topN.fill('3')
  await page.getByRole('spinbutton', { name: 'Applications per week', exact: true }).fill('42')
  const saved = page.waitForResponse((r) => r.url().endsWith('/api/settings') && r.request().method() === 'PUT')
  await page.getByRole('button', { name: 'Save settings', exact: true }).click()
  expect((await saved).ok()).toBeTruthy()
  await page.reload()
  await expect(topN).toHaveValue('3')
  await expect(page.getByRole('spinbutton', { name: 'Applications per week', exact: true })).toHaveValue('42')
  const settings = await request.get('/api/settings')
  expect(settings.ok()).toBeTruthy()
  expect(await settings.json()).toMatchObject({ auto_evaluate_top_n: 3, targets: { applied_per_week: 42 } })
})
